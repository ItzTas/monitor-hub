mod parse;

use std::collections::HashSet;
use std::time::Duration;

use tokio_postgres::Client;

use parse::Problem;

const LOCK_ID: i64 = 4_097_083_626;
const LOCK_RETRY_EVERY: Duration = Duration::from_secs(5);
const LOCK_RETRIES: u32 = 60;
const TABLE_RETRY_EVERY: Duration = Duration::from_secs(1);
const TABLE_RETRIES: u32 = 3;

const TABLE_EXISTS: &str = "SELECT EXISTS ( SELECT 1 FROM pg_tables WHERE (current_schema() IS NULL OR schemaname = current_schema()) AND tablename = 'goose_db_version' )";
const CREATE_TABLE: &str = "CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)";
const INSERT_VERSION: &str =
    "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, $2)";
const LIST_VERSIONS: &str = "SELECT version_id FROM goose_db_version ORDER BY id DESC";

#[derive(Clone, Copy, Debug)]
pub struct Migration {
    pub version: i64,
    pub name: &'static str,
    pub sql: &'static str,
}

#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum MigrateError {
    #[error(
        "migration {migration} uses the goose annotation {annotation:?}, which is not supported"
    )]
    Unsupported {
        migration: String,
        annotation: String,
    },
    #[error("migration {migration} is invalid: {reason}")]
    Invalid { migration: String, reason: String },
    #[error(
        "migration version {missing} is not applied but the database is already at version {current}"
    )]
    OutOfOrder { missing: i64, current: i64 },
    #[error("goose_db_version has no rows, not even the version 0 row goose expects")]
    MissingZeroVersion,
    #[error("another process held the goose migration lock for more than 5 minutes")]
    LockTimeout,
    #[error("migration {migration} failed")]
    Failed {
        migration: String,
        #[source]
        source: tokio_postgres::Error,
    },
    #[error("migration bookkeeping failed")]
    Database(#[from] tokio_postgres::Error),
}

struct Prepared {
    version: i64,
    name: &'static str,
    statements: Vec<String>,
}

pub async fn up(client: &mut Client, migrations: &[Migration]) -> Result<Vec<i64>, MigrateError> {
    let prepared = prepare(migrations)?;
    lock(client).await?;
    let applied = apply(client, &prepared).await;
    let unlocked = client
        .execute("SELECT pg_advisory_unlock($1)", &[&LOCK_ID])
        .await;
    let applied = applied?;
    unlocked?;
    Ok(applied)
}

fn prepare(migrations: &[Migration]) -> Result<Vec<Prepared>, MigrateError> {
    let mut sorted: Vec<&Migration> = migrations.iter().collect();
    sorted.sort_by_key(|migration| migration.version);
    if let Some(migration) = sorted.iter().find(|migration| migration.version < 1) {
        return Err(invalid(
            migration.name,
            "the version must be greater than zero",
        ));
    }
    if let Some(pair) = sorted
        .windows(2)
        .find(|pair| pair[0].version == pair[1].version)
    {
        let reason = format!(
            "version {} is also used by {}",
            pair[1].version, pair[0].name
        );
        return Err(invalid(pair[1].name, &reason));
    }
    sorted
        .into_iter()
        .map(|migration| {
            let statements =
                parse::up_statements(migration.sql).map_err(|problem| match problem {
                    Problem::Unsupported(annotation) => MigrateError::Unsupported {
                        migration: migration.name.to_owned(),
                        annotation,
                    },
                    Problem::Invalid(reason) => invalid(migration.name, &reason),
                })?;
            Ok(Prepared {
                version: migration.version,
                name: migration.name,
                statements,
            })
        })
        .collect()
}

fn invalid(migration: &str, reason: &str) -> MigrateError {
    MigrateError::Invalid {
        migration: migration.to_owned(),
        reason: reason.to_owned(),
    }
}

async fn lock(client: &Client) -> Result<(), MigrateError> {
    for attempt in 0..=LOCK_RETRIES {
        if attempt > 0 {
            tokio::time::sleep(LOCK_RETRY_EVERY).await;
        }
        let row = client
            .query_one("SELECT pg_try_advisory_lock($1)", &[&LOCK_ID])
            .await?;
        if row.try_get(0)? {
            return Ok(());
        }
    }
    Err(MigrateError::LockTimeout)
}

async fn apply(client: &mut Client, prepared: &[Prepared]) -> Result<Vec<i64>, MigrateError> {
    ensure_table(client).await?;
    let rows = client.query(LIST_VERSIONS, &[]).await?;
    if rows.is_empty() {
        return Err(MigrateError::MissingZeroVersion);
    }
    let recorded = rows
        .iter()
        .map(|row| row.try_get(0))
        .collect::<Result<HashSet<i64>, _>>()?;
    let current = recorded.iter().copied().fold(0, i64::max);
    let pending: Vec<&Prepared> = prepared
        .iter()
        .filter(|migration| !recorded.contains(&migration.version))
        .collect();
    if let Some(missing) = pending.iter().find(|migration| migration.version < current) {
        return Err(MigrateError::OutOfOrder {
            missing: missing.version,
            current,
        });
    }
    let mut applied = Vec::with_capacity(pending.len());
    for migration in pending {
        run(client, migration).await?;
        applied.push(migration.version);
    }
    Ok(applied)
}

async fn ensure_table(client: &mut Client) -> Result<(), tokio_postgres::Error> {
    let mut retries = 0;
    loop {
        if client.query_one(TABLE_EXISTS, &[]).await?.try_get(0)? {
            return Ok(());
        }
        match create_table(client).await {
            Ok(()) => return Ok(()),
            Err(err) if retries == TABLE_RETRIES => return Err(err),
            Err(_) => retries += 1,
        }
        tokio::time::sleep(TABLE_RETRY_EVERY).await;
    }
}

async fn create_table(client: &mut Client) -> Result<(), tokio_postgres::Error> {
    let transaction = client.transaction().await?;
    transaction.batch_execute(CREATE_TABLE).await?;
    transaction
        .execute(INSERT_VERSION, &[&0_i64, &true])
        .await?;
    transaction.commit().await
}

async fn run(client: &mut Client, migration: &Prepared) -> Result<(), MigrateError> {
    let failed = |source| MigrateError::Failed {
        migration: migration.name.to_owned(),
        source,
    };
    let transaction = client.transaction().await?;
    for statement in &migration.statements {
        transaction.batch_execute(statement).await.map_err(failed)?;
    }
    transaction
        .execute(INSERT_VERSION, &[&migration.version, &true])
        .await
        .map_err(failed)?;
    transaction.commit().await.map_err(failed)
}
